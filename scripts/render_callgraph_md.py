"""Wrap the Mermaid call graph in a Markdown page (GitHub renders ```mermaid fences)."""

import sys
from pathlib import Path

out = Path(sys.argv[1])
mmd = (out / "callgraph.mmd").read_text()
n_edges = sum(1 for ln in mmd.splitlines() if "-->" in ln)
(out / "callgraph.md").write_text(
    "# Call graph (package level)\n\n"
    f"Generated by `make demo-f1` from `corpus/`. {n_edges} package-to-package edges; "
    "edge labels are call-site counts.\n\n"
    f"```mermaid\n{mmd}```\n"
)
